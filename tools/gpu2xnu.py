#!/usr/bin/env python3
"""
Generate XNU's bsd/dev/sweet_sargo_gpu.c from shim/gpu.c (the sargo Adreno 615
bring-up proven in shim probes t10..t21), so the kernel runs the same code:

  * GPU_GMU_BOOT, GPU_GX_ON, GPU_CP, GPU_ZAP fixed on (the zap path, downstream
    KGSL order: zap before the SQE starts);
  * rd()/wr() take the same physical addresses and go through io_va(), a
    table of ml_io_map windows set up first;
  * the shim's static DMA arrays become one kmem_alloc_contig() block used
    through an uncached (write-combining) alias, PA kept separately;
  * the firmware comes from mkpayload --blob entries in /chosen/memory-map
    (never in git);
  * console lines go to printf ("SWEET GPU: ...");
  * the shim-only EL1 timer shutdown before AUTH_AND_RESET is dropped (XNU
    schedules with those timers).

usage: gpu2xnu.py shim/gpu.c out.c
"""
import re, sys

src = open(sys.argv[1]).read()
body = src[src.index('#define GCC\t'):]

def sub(old, new, count=1):
    global body
    n = body.count(old)
    if n != count:
        sys.exit(f'gpu2xnu: expected {count}x {old!r}, found {n}')
    body = body.replace(old, new)

# machine glue the shim defines itself
sub('static inline uint32_t rd(uintptr_t a) { return *(volatile uint32_t *)a; }\n'
    'static inline void wr(uintptr_t a, uint32_t v) { *(volatile uint32_t *)a = v; __asm__ volatile("dsb sy" ::: "memory"); }\n', '')
i = body.index('static uint64_t ticks(void)')
j = body.index('/* poll until')
body = body[:i] + body[j:]

# DMA arrays -> one contiguous block (uncached alias + PA)
sub('static uint8_t gmu_mem[0x10000] __attribute__((aligned(4096)));\n'
    'static uint64_t pt_l1[512] __attribute__((aligned(4096)));\n'
    'static uint64_t pt_l2[512] __attribute__((aligned(4096)));\n'
    'static uint64_t pt_l3[512] __attribute__((aligned(4096)));\n', '')
sub('static uint8_t gpu_mem[0x10000] __attribute__((aligned(4096)));\n', '')
sub('static uint8_t zap_meta[0x2000] __attribute__((aligned(4096)));\n', '')
sub('extern const uint8_t gmu_fw[], gmu_fw_end[];	/* gmufw.S, generated by build.sh */\n', '')
sub('extern const uint8_t sqe_fw[], sqe_fw_end[];	/* gmufw.S */\n', '')
sub('extern const uint8_t zap_mdt[], zap_mdt_end[], zap_b02[], zap_b02_end[];	/* gmufw.S */\n', '')
body = body.replace('sizeof(gmu_mem)', 'GMU_MEM_SIZE').replace('sizeof(gpu_mem)', 'GPU_MEM_SIZE') \
           .replace('sizeof(zap_meta)', 'ZAP_META_SIZE')
sub('(uintptr_t)gmu_mem + i * 4096u', 'gmu_mem_pa + i * 4096u')
sub('(uintptr_t)gpu_mem + i * 4096u', 'gpu_mem_pa + i * 4096u')
sub('(uintptr_t)pt_l2 | 3u', 'pt_l2_pa | 3u')
sub('(uintptr_t)pt_l3 | 3u', 'pt_l3_pa | 3u')
body = body.replace('(uint32_t)(uintptr_t)pt_l1', '(uint32_t)pt_l1_pa') \
           .replace('(uint64_t)(uintptr_t)pt_l1', 'pt_l1_pa')
body = body.replace('(uint32_t)(uintptr_t)zap_meta', '(uint32_t)zap_meta_pa')
body = body.replace('(uintptr_t)zap_meta', 'zap_meta_pa')  # may be 0 (t23: INIT_IMAGE uses ZAP_REGION)
# CPU views of physical memory outside the DMA block
sub('const uint8_t *db = (const uint8_t *)(uintptr_t)base;', 'const uint8_t *db = (const uint8_t *)io_va_map(base, size);')
body = body.replace('*(volatile uint32_t *)ZAP_REGION', '*(volatile uint32_t *)io_va(ZAP_REGION)')
sub('volatile uint32_t *dst = (volatile uint32_t *)ZAP_REGION;', 'volatile uint32_t *dst = (volatile uint32_t *)io_va(ZAP_REGION);')
sub('volatile uint32_t *reg = (volatile uint32_t *)ZAP_REGION;', 'volatile uint32_t *reg = (volatile uint32_t *)io_va(ZAP_REGION);')
# XNU schedules with the EL1 timers
sub('	__asm__ volatile("msr cntp_ctl_el0, %0; msr cntv_ctl_el0, %0; isb" : : "r"((uint64_t)2));	/* off, masked */\n',
    '	/* (the shim also switched the EL1 timers off here; XNU needs them) */\n')
sub('void test_gpu(void)\n', 'static void test_gpu(void)\n')
body = body.replace('udelay(', 'delay(')

pre = r'''/*
 * GENERATED by tools/gpu2xnu.py from shim/gpu.c - edit the shim, regenerate.
 *
 * SWEET GPU for the Pixel 3a (sargo): Adreno 615 + GMU bring-up, the code of
 * shim probe t21 run inside XNU (MMU/caches on, IRQs serviced) to retry the
 * zap shader load that hangs in TZ PAS AUTH_AND_RESET from the bare shim.
 * Boot-arg sargogpu=1 starts it on a kernel thread from sweet_sdhc_init.
 * Firmware: mkpayload --blob GPU-GMU=a630_gmu.bin --blob GPU-SQE=a630_sqe.fw
 * --blob GPU-ZAP-MDT=a615_zap.mdt --blob GPU-ZAP-B02=a615_zap.b02 (the
 * phone's own /vendor/firmware; not in git).
 */
#if defined(ARM64_BOARD_CONFIG_SWEET)
#include <stdint.h>
#include <sys/param.h>
#include <sys/systm.h>
#include <kern/clock.h>
#include <kern/thread.h>
#include <machine/machine_routines.h>
#include <arm/caches_internal.h>
#include <vm/pmap.h>
#include <vm/vm_kern.h>
#include <pexpert/pexpert.h>
#include <pexpert/device_tree.h>

extern vm_offset_t ml_io_map(vm_offset_t, vm_size_t);
extern vm_offset_t ml_io_map_wcomb(vm_offset_t, vm_size_t);
extern ppnum_t pmap_find_phys(pmap_t, addr64_t);
extern vm_map_address_t phystokv(uint64_t);
void sweet_sargo_gpu_init(void);

/* the shim code casts byte buffers to words and keeps unused diagnostics */
#pragma clang diagnostic ignored "-Wcast-align"
#pragma clang diagnostic ignored "-Wunused-function"
#pragma clang diagnostic ignored "-Wunused-macros"
#pragma clang diagnostic ignored "-Wunused-variable"
#pragma clang diagnostic ignored "-Wmissing-prototypes"
#pragma clang diagnostic ignored "-Wshorten-64-to-32"
#pragma clang diagnostic ignored "-Wsign-conversion"
#pragma clang diagnostic ignored "-Wsign-compare"
#pragma clang diagnostic ignored "-Wimplicit-int-conversion"
#pragma clang diagnostic ignored "-Wdeclaration-after-statement"
#pragma clang diagnostic ignored "-Wmissing-variable-declarations"
#pragma clang diagnostic ignored "-Wcomma"
#pragma clang diagnostic ignored "-Wunknown-warning-option"
#pragma clang diagnostic ignored "-Wbad-function-cast"
#pragma clang diagnostic ignored "-Wc++-keyword"
#pragma clang diagnostic ignored "-Wcast-qual"
#pragma clang diagnostic ignored "-Wpointer-arith"
#pragma clang diagnostic ignored "-Wextra-semi-stmt"
#pragma clang diagnostic ignored "-Wvla"
#pragma clang diagnostic ignored "-Wmissing-noreturn"
#pragma clang diagnostic ignored "-Wunreachable-code"
#pragma clang diagnostic ignored "-Wcovered-switch-default"
#pragma clang diagnostic ignored "-Wstrict-prototypes"
#pragma clang diagnostic ignored "-Wunsafe-buffer-usage"

#define GPU_GMU_BOOT 1
#define GPU_GX_ON 1
#define GPU_CP 1
#define GPU_ZAP 1

/* ---- physical -> virtual windows (ml_io_map) ---- */
static struct { uint64_t pa, size; vm_offset_t va; } io_win[32];
static unsigned io_nwin;

static vm_offset_t
io_va_map(uint64_t pa, uint64_t size)
{
	for (unsigned i = 0; i < io_nwin; i++)
		if (pa >= io_win[i].pa && pa + 4 <= io_win[i].pa + io_win[i].size)
			return io_win[i].va + (vm_offset_t)(pa - io_win[i].pa);
	uint64_t base = pa & ~(uint64_t)PAGE_MASK;
	uint64_t len = (pa + size - base + PAGE_MASK) & ~(uint64_t)PAGE_MASK;
	vm_offset_t va = io_nwin < 32 ? ml_io_map((vm_offset_t)base, (vm_size_t)len) : 0;
	if (!va) {
		panic("SWEET GPU: cannot map %#llx", pa);
	}
	io_win[io_nwin].pa = base;
	io_win[io_nwin].size = len;
	io_win[io_nwin++].va = va;
	return va + (vm_offset_t)(pa - base);
}

/*
 * x21: mapping page by page ran out of the 16 slots at the first GPU core
 * register (RBBM_STATUS 0x5000840, panic): map the blocks whole up front.
 */
static void
io_premap(void)
{
	static const struct { uint64_t pa, size; } blocks[] = {
		{0x00100000, 0x1f0000},	/* GCC */
		{0x05000000, 0x0a0000},	/* GPU, GPU SMMU, GMU (+RSCC, AO), GPU CC */
		{0x0b280000, 0x010000},	/* GPU PDC */
		{0x0b480000, 0x010000},	/* GPU PDC sequencer */
		{0x0c3f0000, 0x001000},	/* AOP message RAM (cmd-db locator) */
		{0x179e0000, 0x004000},	/* apps RSC DRV 2 */
		{0x17a00000, 0x010000},	/* GICD */
		{0x17a60000, 0x020000},	/* GICR CPU 0 */
		{0x95c14000, 0x004000},	/* zap region 0x95c15000 (stock DT) */
	};
	for (unsigned i = 0; i < sizeof(blocks) / sizeof(blocks[0]); i++)
		(void)io_va_map(blocks[i].pa, blocks[i].size);
}

static vm_offset_t
io_va(uint64_t pa)
{
	return io_va_map(pa, 4);
}

static inline uint32_t rd(uint64_t a)
{
	uint32_t v = *(volatile uint32_t *)io_va(a);
	__asm__ volatile("dmb osh" ::: "memory");
	return v;
}

static inline void wr(uint64_t a, uint32_t v)
{
	__asm__ volatile("dmb osh" ::: "memory");
	*(volatile uint32_t *)io_va(a) = v;
	__asm__ volatile("dsb sy" ::: "memory");
}

static void
con_str(const char *label, const char *s)
{
	printf("SWEET GPU: %-8s %s\n", label, s);
}

static void
con_hex2(const char *label, const char *a, uint32_t va, const char *b, uint32_t vb)
{
	printf("SWEET GPU: %-8s %s%08x %s%08x\n", label, a ? a : "", va, b ? b : "", vb);
}

/* ---- DMA block: GMU 64K, GPU 64K, SMMU tables, TZ metadata ---- */
#define GMU_MEM_SIZE	0x10000
#define GPU_MEM_SIZE	0x10000
#define ZAP_META_SIZE	0x2000
#define DMA_GMU		0x00000
#define DMA_GPU		0x10000
#define DMA_PT1		0x20000
#define DMA_PT2		0x21000
#define DMA_PT3		0x22000
#define DMA_META	0x24000
#define DMA_SIZE	0x28000
static uint8_t *gmu_mem, *gpu_mem, *zap_meta;
static uint64_t *pt_l1, *pt_l2, *pt_l3;
static uint64_t gmu_mem_pa, gpu_mem_pa, zap_meta_pa, pt_l1_pa, pt_l2_pa, pt_l3_pa;

/* ---- firmware blobs from /chosen/memory-map ---- */
static const uint8_t *gmu_fw, *gmu_fw_end, *sqe_fw, *sqe_fw_end;
static const uint8_t *zap_mdt, *zap_mdt_end, *zap_b02, *zap_b02_end;

'''

post = r'''

static bool
blob(const char *name, const uint8_t **start, const uint8_t **end)
{
	DTEntry mm;
	const uint64_t *p = NULL;
	unsigned int size = 0;
	if (SecureDTLookupEntry(NULL, "/chosen/memory-map", &mm) != kSuccess ||
	    SecureDTGetProperty(mm, name, (void const **)&p, &size) != kSuccess || size < 16 ||
	    p[1] == 0 || p[1] > 0x100000) {
		printf("SWEET GPU: no %s in /chosen/memory-map\n", name);
		return false;
	}
	/* mkpayload pads blobs to whole pages; the real length is the first word */
	const uint8_t *va = (const uint8_t *)phystokv(p[0]);
	uint32_t len = *(const uint32_t *)va;
	if (len == 0 || len + 16 > p[1]) {
		printf("SWEET GPU: %s bad length %u\n", name, len);
		return false;
	}
	*start = va + 16;
	*end = va + 16 + len;
	return true;
}

static void
gpu_thread(void *arg, wait_result_t result)
{
	(void)arg;
	(void)result;
	vm_offset_t dma = 0;
	if (!blob("GPU-GMU", &gmu_fw, &gmu_fw_end) || !blob("GPU-SQE", &sqe_fw, &sqe_fw_end) ||
	    !blob("GPU-ZAP-MDT", &zap_mdt, &zap_mdt_end) || !blob("GPU-ZAP-B02", &zap_b02, &zap_b02_end)) {
		return;
	}
	if (kmem_alloc_contig(kernel_map, &dma, DMA_SIZE, PAGE_MASK, 0, 0,
	    KMA_DATA | KMA_ZERO | KMA_PERMANENT, VM_KERN_MEMORY_IOKIT) != KERN_SUCCESS) {
		printf("SWEET GPU: no contiguous DMA memory\n");
		return;
	}
	uint64_t pa = ptoa_64(pmap_find_phys(kernel_pmap, (addr64_t)dma));
	/* only the uncached alias is used from here on: drop the cacheable lines */
	flush_dcache64((addr64_t)pa, DMA_SIZE, TRUE);
	uint8_t *wc = (uint8_t *)ml_io_map_wcomb((vm_offset_t)pa, DMA_SIZE);
	if (!pa || !wc) {
		printf("SWEET GPU: DMA mapping failed\n");
		return;
	}
	gmu_mem = wc + DMA_GMU;        gmu_mem_pa = pa + DMA_GMU;
	gpu_mem = wc + DMA_GPU;        gpu_mem_pa = pa + DMA_GPU;
	pt_l1 = (uint64_t *)(wc + DMA_PT1); pt_l1_pa = pa + DMA_PT1;
	pt_l2 = (uint64_t *)(wc + DMA_PT2); pt_l2_pa = pa + DMA_PT2;
	pt_l3 = (uint64_t *)(wc + DMA_PT3); pt_l3_pa = pa + DMA_PT3;
	zap_meta = wc + DMA_META;      zap_meta_pa = pa + DMA_META;
	printf("SWEET GPU: DMA %#llx (%#x bytes), firmware gmu %ld sqe %ld mdt %ld b02 %ld\n",
	    pa, DMA_SIZE, (long)(gmu_fw_end - gmu_fw), (long)(sqe_fw_end - sqe_fw),
	    (long)(zap_mdt_end - zap_mdt), (long)(zap_b02_end - zap_b02));
	io_premap();
	test_gpu();
	printf("SWEET GPU: thread done\n");
}

void
sweet_sargo_gpu_init(void)
{
	static bool started;
	int enabled = 0;
	thread_t thread;
	if (started) {
		return;
	}
	started = true;
	(void)PE_parse_boot_argn("sargogpu", &enabled, sizeof(enabled));
	if (!enabled) {
		return;
	}
	if (kernel_thread_start(gpu_thread, NULL, &thread) == KERN_SUCCESS) {
		thread_deallocate(thread);
	}
}
#endif /* ARM64_BOARD_CONFIG_SWEET */
'''
open(sys.argv[2], 'w').write(pre + body + post)
